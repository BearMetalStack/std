/**
 * Generates `utilities.css`: single-purpose classes over the defaults layer's
 * scales (`gap-4` is `gap: var(--space-4)`), plus a handful of layout classes
 * that have no token behind them (`flex`, `items-center`, …).
 *
 * The scale classes are read off the tokens the defaults layer defines, so a
 * step added to `space`, `radius` or `shadow` gets its classes the next time
 * this runs, and a class can never name a step that doesn't exist. Every value
 * is a `var()`, which is what lets `[data-density]` and a theme's overrides
 * reach markup that only uses classes.
 *
 * Utilities are unlayered and one class deep. A component rule of equal
 * specificity declared after them still wins, so adopting them in a template
 * never fights the component's own stylesheet.
 *
 * Run with `deno task bm:css` from `drip/` (which embeds the result).
 *
 * @module
 */

import { withDefaultTokens } from "../theme.ts";
import { definedProperties } from "./generate.ts";
import type { Theme } from "../types.ts";

/** Property groups each scale step expands into: class suffix → declarations. */
const SPACE_FAMILIES: Record<string, string[]> = {
	"gap": ["gap"],
	"gap-x": ["column-gap"],
	"gap-y": ["row-gap"],
	"p": ["padding"],
	"px": ["padding-inline"],
	"py": ["padding-block"],
	"pt": ["padding-top"],
	"pr": ["padding-right"],
	"pb": ["padding-bottom"],
	"pl": ["padding-left"],
	"m": ["margin"],
	"mx": ["margin-inline"],
	"my": ["margin-block"],
	"mt": ["margin-top"],
	"mr": ["margin-right"],
	"mb": ["margin-bottom"],
	"ml": ["margin-left"],
};

/** Classes with no scale behind them. */
const LAYOUT: Record<string, string> = {
	"flex": "display: flex",
	"inline-flex": "display: inline-flex",
	"grid": "display: grid",
	"block": "display: block",
	"flex-row": "flex-direction: row",
	"flex-col": "flex-direction: column",
	"flex-wrap": "flex-wrap: wrap",
	"items-start": "align-items: flex-start",
	"items-center": "align-items: center",
	"items-end": "align-items: flex-end",
	"items-stretch": "align-items: stretch",
	"items-baseline": "align-items: baseline",
	"justify-start": "justify-content: flex-start",
	"justify-center": "justify-content: center",
	"justify-end": "justify-content: flex-end",
	"justify-between": "justify-content: space-between",
	"self-center": "align-self: center",
	"flex-1": "flex: 1 1 0%",
	"flex-auto": "flex: 1 1 auto",
	"flex-none": "flex: none",
	"grow": "flex-grow: 1",
	"shrink-0": "flex-shrink: 0",
	"min-w-0": "min-width: 0",
	"min-h-0": "min-height: 0",
	"w-full": "width: 100%",
	"h-full": "height: 100%",
	"overflow-auto": "overflow: auto",
	"overflow-hidden": "overflow: hidden",
	"overflow-y-auto": "overflow-y: auto",
	"truncate": "overflow: hidden; text-overflow: ellipsis; white-space: nowrap",
	"mx-auto": "margin-inline: auto",
	"ml-auto": "margin-left: auto",
};

/** Steps of `--<scale>-*` that aren't sizes to make classes of. */
const SKIP: Record<string, Set<string>> = {
	space: new Set(["unit"]),
	radius: new Set(["base"]),
	shadow: new Set(["focus"]),
};

function steps(defined: Set<string>, scale: string): string[] {
	const prefix = `--${scale}-`;
	return [...defined]
		.filter((p) => p.startsWith(prefix))
		.map((p) => p.slice(prefix.length))
		// `radius-scale-*` are the multipliers, not radii.
		.filter((s) => !s.includes("scale") && !SKIP[scale]?.has(s))
		.sort((a, b) => order(a) - order(b));
}

/** Numeric steps in size order (`0-5` is 0.5); named ones keep their place after. */
function order(step: string): number {
	const n = Number(step.replace("-", "."));
	return Number.isNaN(n) ? Infinity : n;
}

/** One rule, laid out the way `deno fmt` lays it out, so the file stays formatted. */
const rule = (cls: string, body: string) =>
	`.${cls} {\n${body.split("; ").map((d) => `\t${d};`).join("\n")}\n}`;

/** The text of `utilities.css`. */
export async function renderUtilities(): Promise<string> {
	const defaults = (await import("../themes/_defaults.theme.json", { with: { type: "json" } }))
		.default;
	const defined = definedProperties(await withDefaultTokens(defaults as unknown as Theme));

	const out: string[] = [
		"/* AUTO-GENERATED by `deno task bm:css` (css/utilities.ts) — do not edit. */",
		"",
		"/* ---- layout ---- */",
		...Object.entries(LAYOUT).map(([cls, body]) => rule(cls, body)),
		"",
		"/* Composites: a centred row and a column, each overridable by any gap-*. */",
		rule("row", "display: flex; align-items: center; gap: var(--space-2)"),
		rule("stack", "display: flex; flex-direction: column; gap: var(--space-2)"),
	];

	for (const [family, props] of Object.entries(SPACE_FAMILIES)) {
		out.push("", `/* ---- ${family}-* ---- */`);
		for (const step of steps(defined, "space")) {
			out.push(
				rule(`${family}-${step}`, props.map((p) => `${p}: var(--space-${step})`).join("; ")),
			);
		}
	}

	out.push("", "/* ---- rounded-* ---- */");
	for (const step of steps(defined, "radius")) {
		out.push(rule(`rounded-${step}`, `border-radius: var(--radius-${step})`));
	}
	out.push(rule("rounded", "border-radius: var(--radius-base)"));

	out.push("", "/* ---- shadow-* ---- */");
	for (const step of steps(defined, "shadow")) {
		out.push(rule(`shadow-${step}`, `box-shadow: var(--shadow-${step})`));
	}
	out.push(rule("shadow", "box-shadow: var(--shadow-base)"));

	// Last, so it beats every display class above it.
	out.push("", "/* ---- hidden ---- */", rule("hidden", "display: none !important"));

	return out.join("\n") + "\n";
}

if (import.meta.main) {
	await Deno.writeTextFile(new URL("./utilities.css", import.meta.url), await renderUtilities());
	console.log("Drip: generated utilities.css.");
}
