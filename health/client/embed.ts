/**
 * Bundles the dashboard components for the browser and embeds the result in `embedded.ts`, so
 * `healthModule` can serve them without a bundler at runtime (and from a `deno compile` binary).
 *
 * Run with `deno task bm:embed` after changing anything under `components/`.
 */

const entry = new URL("./entry.ts", import.meta.url);
const out = new URL("./embedded.ts", import.meta.url);

const result = await Deno.bundle({
	entrypoints: [entry.href],
	write: false,
	platform: "browser",
	format: "esm",
	minify: true,
});

for (const message of [...result.errors, ...result.warnings]) console.warn(message);
const script = result.outputFiles?.find((f) => !f.path.endsWith(".css"))?.text();
if (!result.success || !script) {
	console.error("Bundling the dashboard client failed");
	Deno.exit(1);
}

await Deno.writeTextFile(
	out,
	`// Generated by \`deno task bm:embed\`. Do not edit.\n` +
		`/** The standalone dashboard's client bundle. */\n` +
		`export const clientScript: string = ${JSON.stringify(script)};\n`,
);
console.log(`Embedded ${(script.length / 1024).toFixed(1)} KiB into ${out.pathname}`);
